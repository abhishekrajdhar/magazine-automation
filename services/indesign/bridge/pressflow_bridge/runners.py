"""Ways of running an ExtendScript file in InDesign.

All runners pass the script a single argument: the path of a JSON args file
(``arguments[0]`` inside ExtendScript). The InDesign Server runner additionally sends every
argument as SOAP ``scriptArgs`` (readable via ``app.scriptArgs``), which is how InDesign
Server scripts conventionally receive input.

* ``MacDesktopRunner``  - macOS, InDesign desktop, via ``osascript`` + AppleScript ``do script``.
* ``WindowsComRunner``  - Windows, InDesign desktop, via COM ``DoScript`` (needs pywin32).
* ``ServerSoapRunner``  - InDesign Server, via SOAP ``RunScript`` (stdlib HTTP + XML).
"""

from __future__ import annotations

import logging
import re
import shutil
import subprocess
import sys
import threading
import time
import urllib.error
import urllib.request
import xml.etree.ElementTree as ET
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Callable, Protocol
from xml.sax.saxutils import escape

from .config import Config

log = logging.getLogger("pressflow.runner")


@dataclass
class RunResult:
    ok: bool
    error: str | None = None
    script_result: str | None = None
    returncode: int | None = None
    stdout: str = ""
    stderr: str = ""
    duration_ms: int = 0
    details: dict[str, Any] = field(default_factory=dict)


class Runner(Protocol):
    name: str

    def run_script(self, jsx: Path, args: dict[str, str], args_file: Path, timeout: float) -> RunResult: ...

    def diagnose(self) -> tuple[bool, str]: ...


# ---------------------------------------------------------------------- macOS desktop
APPLESCRIPT_TEMPLATE = """\
-- Generated by the PressFlow InDesign bridge.
-- argv: 1 = ExtendScript path, 2 = JSON args file, 3 = timeout in seconds
on run argv
\tset jsxPath to item 1 of argv
\tset argsPath to item 2 of argv
\tset timeoutSec to (item 3 of argv) as integer
\tset jsxFile to POSIX file jsxPath
\twith timeout of timeoutSec seconds
\t\ttell application id "{app_id}"
\t\t\tset scriptResult to do script jsxFile language javascript with arguments {{argsPath}}
\t\tend tell
\tend timeout
\ttry
\t\treturn scriptResult as text
\ton error
\t\treturn ""
\tend try
end run
"""

_APP_ID_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9.\-]*$")


def build_applescript(app_id: str) -> str:
    """AppleScript source. Paths travel as argv (no quoting issues); only the validated
    bundle id is interpolated, because ``tell application id`` must be a literal for the
    InDesign dictionary terms (``do script``, ``language javascript``) to compile."""
    if not _APP_ID_RE.match(app_id):
        raise ValueError(f"invalid application bundle id: {app_id!r}")
    return APPLESCRIPT_TEMPLATE.format(app_id=app_id)


def build_osascript_command(script_path: Path, jsx: Path, args_file: Path, timeout: float) -> list[str]:
    return ["osascript", str(script_path), str(jsx), str(args_file), str(int(max(1, timeout)))]


class MacDesktopRunner:
    name = "macos-osascript"

    def __init__(self, app_id: str = "com.adobe.InDesign", run: Callable[..., subprocess.CompletedProcess] = subprocess.run) -> None:
        self.app_id = app_id
        self._run = run
        self._script = build_applescript(app_id)

    def run_script(self, jsx: Path, args: dict[str, str], args_file: Path, timeout: float) -> RunResult:
        script_path = args_file.with_name(args_file.stem + ".applescript")
        script_path.write_text(self._script, encoding="utf-8")
        cmd = build_osascript_command(script_path, jsx, args_file, timeout)
        t0 = time.monotonic()
        try:
            # osascript gets a little longer than the AppleScript timeout so the AppleEvent
            # timeout error (-1712) surfaces instead of a hard kill.
            proc = self._run(cmd, capture_output=True, text=True, timeout=timeout + 30)
        except subprocess.TimeoutExpired:
            return RunResult(False, error=f"osascript timed out after {int(timeout + 30)}s (InDesign may still be busy)", duration_ms=_ms(t0))
        except FileNotFoundError:
            return RunResult(False, error="osascript not found (the macOS desktop runner only works on macOS)", duration_ms=_ms(t0))
        ok = proc.returncode == 0
        err = None if ok else (proc.stderr.strip() or f"osascript exited with {proc.returncode}")
        return RunResult(ok, error=err, script_result=proc.stdout.strip() or None, returncode=proc.returncode,
                         stdout=proc.stdout, stderr=proc.stderr, duration_ms=_ms(t0))

    def diagnose(self) -> tuple[bool, str]:
        if sys.platform != "darwin":
            return False, "macOS desktop runner selected but this is not macOS"
        if not shutil.which("osascript"):
            return False, "osascript not found"
        mdfind = shutil.which("mdfind")
        if mdfind:
            try:
                out = self._run([mdfind, f"kMDItemCFBundleIdentifier == '{self.app_id}'"], capture_output=True, text=True, timeout=20)
                paths = [p for p in out.stdout.splitlines() if p.strip()]
            except (subprocess.TimeoutExpired, OSError):
                paths = []
            if paths:
                return True, "InDesign found: " + ", ".join(paths[:3])
        return False, f"no application with bundle id {self.app_id} found (Spotlight); set INDESIGN_APP_ID if it differs"


# ---------------------------------------------------------------------- Windows desktop
SCRIPT_LANGUAGE_JAVASCRIPT = 1246973031  # ScriptLanguage.JAVASCRIPT, four-char code 'JSLg'


class WindowsComRunner:
    name = "windows-com"

    def __init__(self, prog_id: str = "InDesign.Application") -> None:
        self.prog_id = prog_id

    def run_script(self, jsx: Path, args: dict[str, str], args_file: Path, timeout: float) -> RunResult:
        try:
            import pythoncom  # type: ignore[import-not-found]
            import win32com.client  # type: ignore[import-not-found]
        except ImportError:
            return RunResult(False, error="pywin32 is not installed (pip install 'pressflow-indesign-bridge[windows]')")
        holder: dict[str, Any] = {}
        t0 = time.monotonic()

        def target() -> None:
            pythoncom.CoInitialize()
            try:
                app = win32com.client.Dispatch(self.prog_id)
                holder["result"] = app.DoScript(str(jsx), SCRIPT_LANGUAGE_JAVASCRIPT, [str(args_file)])
            except Exception as exc:  # noqa: BLE001 - COM errors are arbitrary
                holder["error"] = f"COM DoScript failed: {exc!r}"
            finally:
                pythoncom.CoUninitialize()

        thread = threading.Thread(target=target, name="indesign-com", daemon=True)
        thread.start()
        thread.join(timeout)
        if thread.is_alive():
            return RunResult(False, error=f"COM DoScript timed out after {int(timeout)}s (InDesign may still be busy)", duration_ms=_ms(t0))
        if "error" in holder:
            return RunResult(False, error=holder["error"], duration_ms=_ms(t0))
        res = holder.get("result")
        return RunResult(True, script_result=None if res is None else str(res), duration_ms=_ms(t0))

    def diagnose(self) -> tuple[bool, str]:
        if sys.platform != "win32":
            return False, "Windows COM runner selected but this is not Windows"
        try:
            import win32com.client  # type: ignore[import-not-found]  # noqa: F401
        except ImportError:
            return False, "pywin32 is not installed"
        try:
            import winreg  # type: ignore[import-not-found]

            with winreg.OpenKey(winreg.HKEY_CLASSES_ROOT, self.prog_id):
                return True, f"COM class {self.prog_id} is registered"
        except OSError:
            return False, f"COM class {self.prog_id} is not registered (is InDesign installed? set INDESIGN_COM_PROGID)"


# ---------------------------------------------------------------------- InDesign Server
SOAP_ENV_NS = "http://schemas.xmlsoap.org/soap/envelope/"
IDSP_NS = "http://ns.adobe.com/InDesign/soap/"


def build_soap_envelope(*, script_file: str | None = None, script_text: str | None = None,
                        args: dict[str, str] | None = None, language: str = "javascript") -> bytes:
    """SOAP 1.1 RunScript request as defined by the InDesign Server IDSP WSDL."""
    if bool(script_file) == bool(script_text):
        raise ValueError("exactly one of script_file / script_text is required")
    lines = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        f'<SOAP-ENV:Envelope xmlns:SOAP-ENV="{SOAP_ENV_NS}" '
        'xmlns:SOAP-ENC="http://schemas.xmlsoap.org/soap/encoding/" '
        'xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" '
        'xmlns:xsd="http://www.w3.org/2001/XMLSchema" '
        f'xmlns:IDSP="{IDSP_NS}">',
        "<SOAP-ENV:Body>",
        "<IDSP:RunScript>",
        "<runScriptParameters>",
        f"<scriptLanguage>{escape(language)}</scriptLanguage>",
    ]
    if script_file:
        lines.append(f"<scriptFile>{escape(script_file)}</scriptFile>")
    else:
        lines.append(f"<scriptText>{escape(script_text or '')}</scriptText>")
    for name, value in (args or {}).items():
        lines.append(f"<scriptArgs><name>{escape(str(name))}</name><value>{escape(str(value))}</value></scriptArgs>")
    lines += ["</runScriptParameters>", "</IDSP:RunScript>", "</SOAP-ENV:Body>", "</SOAP-ENV:Envelope>"]
    return "\n".join(lines).encode("utf-8")


@dataclass
class SoapResult:
    error_number: int
    error_string: str
    script_result: str | None
    fault: str | None = None


def _local(tag: str) -> str:
    return tag.rsplit("}", 1)[-1]


def parse_soap_response(body: bytes) -> SoapResult:
    try:
        root = ET.fromstring(body)
    except ET.ParseError as exc:
        return SoapResult(-1, f"invalid SOAP response: {exc}", None, fault="parse error")
    fault = next((el for el in root.iter() if _local(el.tag) == "Fault"), None)
    if fault is not None:
        fs = next((el.text or "" for el in fault.iter() if _local(el.tag) in ("faultstring", "Text")), "SOAP fault")
        return SoapResult(-1, fs.strip(), None, fault=fs.strip())
    err_no, err_str, result = 0, "", None
    for el in root.iter():
        name = _local(el.tag)
        if name == "errorNumber" and el.text and el.text.strip():
            try:
                err_no = int(el.text.strip())
            except ValueError:
                err_no = -1
        elif name == "errorString":
            err_str = (el.text or "").strip()
        elif name == "scriptResult":
            data = next((d for d in el.iter() if _local(d.tag) == "data"), None)
            result = (data.text if data is not None else el.text) or None
    return SoapResult(err_no, err_str, result)


class ServerSoapRunner:
    name = "indesign-server-soap"

    def __init__(self, server_url: str, opener: Callable[..., Any] = urllib.request.urlopen) -> None:
        self.server_url = server_url
        self._open = opener

    def _post(self, envelope: bytes, timeout: float) -> bytes:
        req = urllib.request.Request(
            self.server_url,
            data=envelope,
            method="POST",
            headers={"Content-Type": "text/xml; charset=utf-8", "SOAPAction": '""'},
        )
        try:
            with self._open(req, timeout=timeout) as resp:
                return resp.read()
        except urllib.error.HTTPError as exc:
            # SOAP faults are delivered with HTTP 500; keep the body so the fault text is reported.
            return exc.read()

    def run_script(self, jsx: Path, args: dict[str, str], args_file: Path, timeout: float) -> RunResult:
        script_args = dict(args)
        script_args["argsFile"] = str(args_file)
        envelope = build_soap_envelope(script_file=str(jsx), args=script_args)
        t0 = time.monotonic()
        try:
            body = self._post(envelope, timeout)
        except (urllib.error.URLError, TimeoutError, ConnectionError, OSError) as exc:
            return RunResult(False, error=f"InDesign Server request to {self.server_url} failed: {getattr(exc, 'reason', exc)}", duration_ms=_ms(t0))
        res = parse_soap_response(body)
        if res.fault or res.error_number != 0:
            msg = res.fault or f"RunScript errorNumber={res.error_number}: {res.error_string}"
            return RunResult(False, error=msg, script_result=res.script_result, duration_ms=_ms(t0))
        return RunResult(True, script_result=res.script_result, duration_ms=_ms(t0))

    def diagnose(self) -> tuple[bool, str]:
        envelope = build_soap_envelope(script_text="app.name + ' ' + app.version")
        try:
            body = self._post(envelope, 30)
        except (urllib.error.URLError, TimeoutError, ConnectionError, OSError) as exc:
            return False, f"InDesign Server not reachable at {self.server_url}: {getattr(exc, 'reason', exc)}"
        res = parse_soap_response(body)
        if res.fault or res.error_number != 0:
            return False, f"InDesign Server answered with an error: {res.fault or res.error_string}"
        return True, f"InDesign Server reachable: {res.script_result}"


def _ms(t0: float) -> int:
    return int((time.monotonic() - t0) * 1000)


def make_runner(config: Config) -> Runner:
    if config.mode == "server":
        return ServerSoapRunner(config.server_url)
    if sys.platform == "darwin":
        return MacDesktopRunner(config.app_id)
    if sys.platform == "win32":
        return WindowsComRunner(config.com_prog_id)
    raise RuntimeError(f"INDESIGN_MODE=desktop is not supported on {sys.platform}; InDesign desktop runs on macOS and Windows only")
